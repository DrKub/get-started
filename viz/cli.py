"""python -m viz: render the report figures from measurement runs."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import style
from .figures import FIGURES
from .load import load_runs

DEFAULT_DATA_DIR = Path("data/runs")
DEFAULT_OUT_DIR = Path("figures")


def _labels(pairs: list[str]) -> dict[str, str]:
    out = {}
    for pair in pairs:
        name, sep, label = pair.partition("=")
        if not sep or not name or not label:
            raise argparse.ArgumentTypeError(f"--label expects RUN_DIR=LABEL, got {pair!r}")
        out[name] = label
    return out


def write_readme(out_dir: Path, runs, stems: list[str], formats: tuple[str, ...]) -> Path:
    lines = [
        "# Figures",
        "",
        "Generated by `python -m viz` from "
        + ", ".join(f"`{r.name}` ({r.label})" for r in runs)
        + ". Do not edit by hand; regenerate with "
        "`pip install -r viz/requirements.txt && python -m viz [--data-dir DIR]`.",
        "",
    ]
    for stem in stems:
        caption = FIGURES[stem][1]
        files = " · ".join(f"[{fmt.upper()}]({stem}.{fmt})" for fmt in formats)
        lines.append(f"- **{stem}** — {caption} ({files})")
    lines.append("")
    path = out_dir / "README.md"
    path.write_text("\n".join(lines))
    return path


def render(data_dir: Path, out_dir: Path, *, labels: dict[str, str] | None = None,
           formats: tuple[str, ...] = ("png", "svg"), only: list[str] | None = None,
           readme: bool = True) -> list[Path]:
    runs = load_runs(data_dir, labels)
    if not runs:
        raise SystemExit(f"no run directories with block_observations under {data_dir}")
    style.apply()
    stems = [s for s in FIGURES if not only or s in only]
    written = []
    for stem in stems:
        fn, _ = FIGURES[stem]
        written += style.save(fn(runs), out_dir, stem, formats)
    if readme:
        written.append(write_readme(out_dir, runs, stems, formats))
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m viz", description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR,
                        help="directory of run folders, or a single run folder (default: data/runs)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="output directory (default: figures)")
    parser.add_argument("--label", action="append", default=[], metavar="RUN_DIR=LABEL",
                        help="display label for a run directory, e.g. 20261029T094113Z='run 3'")
    parser.add_argument("--format", action="append", dest="formats", choices=["png", "svg", "pdf"],
                        help="output format; repeatable (default: png and svg)")
    parser.add_argument("--only", action="append", choices=list(FIGURES), help="render only these figures")
    parser.add_argument("--no-readme", action="store_true", help="do not write README.md captions")
    args = parser.parse_args(argv)
    try:
        labels = _labels(args.label)
    except argparse.ArgumentTypeError as exc:
        parser.error(str(exc))
    written = render(args.data_dir, args.out_dir, labels=labels,
                     formats=tuple(args.formats or ("png", "svg")), only=args.only,
                     readme=not args.no_readme)
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
